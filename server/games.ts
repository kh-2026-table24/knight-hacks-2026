import { access, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { SavedHouse } from "../src/game/generation/generateHouse";
import type { Game, SavedGame } from "../src/game/generation/output/output";
import { testOutput } from "./prompts/test-output";

// Everything for a game lives in server/games/<gameId>/: game.json plus assets/.
const GAMES_DIR = join(import.meta.dirname, "games");
// Houses written by scripts/gen-house.ts (file names start with a timestamp, so they sort oldest first).
const HOUSES_DIR = join(import.meta.dirname, "..", "generated", "houses");
export const gameDir = (gameId: string) => join(GAMES_DIR, gameId);

/** Ids become directory and file names: letters, digits, _ . - only, and no leading dot. */
export const isSafeId = (id: string) => /^(?!\.)[\w.-]+$/.test(id);

const games = new Map<string, Promise<SavedGame>>();

/** The saved game, or (if `create`) a newly created one. Undefined if it doesn't exist and `create` is false. */
export async function getGame(gameId: string, create: boolean): Promise<SavedGame | undefined> {
  const file = join(gameDir(gameId), "game.json");
  if (!games.has(gameId) && !create && !(await access(file).then(() => true, () => false))) return undefined;

  let game = games.get(gameId);
  if (!game) {
    game = loadOrCreate(gameId, file);
    games.set(gameId, game);
    game.catch(() => games.delete(gameId));
  }
  return game;
}

async function loadOrCreate(gameId: string, file: string): Promise<SavedGame> {
  try {
    return JSON.parse(await readFile(file, "utf8")) as SavedGame;
  } catch (error) {
    if ((error as { code?: string }).code !== "ENOENT") throw error;
  }

  const game: SavedGame = { ...(await newGame(gameId)), id: gameId };
  await mkdir(gameDir(gameId), { recursive: true });
  await writeFile(file, JSON.stringify(game, null, 2));
  return game;
}

/**
 * A new game starts from a house generated by scripts/gen-house.ts: the one whose file name contains
 * the game id, otherwise the newest. With no saved houses, it's the hand-written test game.
 */
async function newGame(gameId: string): Promise<Game> {
  const names = (await readdir(HOUSES_DIR).catch(() => [] as string[])).filter((n) => n.endsWith(".json")).sort();
  const name = names.find((n) => n.includes(gameId)) ?? names.at(-1);
  if (!name) {
    console.log(`[${gameId}] creating game from the test game (no saved houses; run npx tsx scripts/gen-house.ts)`);
    return JSON.parse(testOutput()) as Game;
  }
  const house = JSON.parse(await readFile(join(HOUSES_DIR, name), "utf8")) as SavedHouse;
  console.log(`[${gameId}] creating game from house "${house.title}" (${name})`);
  return house.game;
}
